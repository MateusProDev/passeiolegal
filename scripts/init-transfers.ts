function generateSlug(name: string): string {
  return name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-');
}

async function initializeTransfers() {
  const { adminDb } = await import('../src/lib/firebase-admin');

  if (!adminDb) {
    throw new Error('Firebase Admin não está inicializado; verifique as credenciais da Vercel.');
  }

  const transfersRef = adminDb.collection('transfers');
  const snapshot = await transfersRef.get();
  const existingKeys = new Set<string>();
  const existingIds = new Set(snapshot.docs.map((document) => document.id));

  for (const document of snapshot.docs) {
    const data = document.data();
    if (typeof data.slug === 'string') existingKeys.add(data.slug);
    if (typeof data.name === 'string') existingKeys.add(generateSlug(data.name));
  }

  const missing = transfers.filter((transfer) => !existingKeys.has(generateSlug(transfer.name)));
  const batch = adminDb.batch();
  const now = new Date();

  for (const transfer of missing) {
    const slug = generateSlug(transfer.name);
    if (existingIds.has(slug)) {
      throw new Error(`O ID "${slug}" já está em uso por outro documento.`);
    }

    batch.create(transfersRef.doc(slug), {
      ...transfer,
      slug,
      imageUrl: '',
      imageAlt: transfer.name,
      galleryImages: [],
      includesItems: [],
      excludesItems: [],
      vehicleType: 'Consulte',
      capacity: 15,
      active: true,
      createdAt: now,
      updatedAt: now,
    });
  }

  if (missing.length > 0) await batch.commit();

  console.log(JSON.stringify({
    requested: transfers.length,
    inserted: missing.length,
    alreadyPresent: transfers.length - missing.length,
  }));
}

if (require.main === module) {
  initializeTransfers()
    .then(() => process.exit(0))
    .catch((error) => {
      console.error('Falha ao inicializar transfers:', error);
      process.exit(1);
    });
}

export { initializeTransfers };
